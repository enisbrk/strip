import AppKit
import StripCore

/// strip:// URLs, the `strip` command-line tool and Raycast script commands.
///
///   strip://run/<command>     e.g. strip://run/focus-left, strip://run/stack-right
///   strip://layout/<layout>   strip, full, twoColumns, grid2x2, …
///   strip://enable · strip://disable · strip://restart
@MainActor
enum Automation {
    static let supportFolder = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/Strip", isDirectory: true)
    static let raycastFolder = supportFolder.appendingPathComponent("Raycast", isDirectory: true)
    static let cliURL = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".local/bin/strip")

    enum Action {
        case run(Command)
        case layout(LayoutPreset)
        case enable, disable, restart
    }

    static func action(for url: URL) -> Action? {
        guard url.scheme == "strip" else { return nil }
        let argument = url.pathComponents.dropFirst().first ?? ""
        switch url.host {
        case "run": return Command(id: argument).map(Action.run)
        case "layout": return LayoutPreset(rawValue: argument).map(Action.layout)
        case "enable": return .enable
        case "disable": return .disable
        case "restart": return .restart
        default: return nil
        }
    }

    // MARK: Command-line tool

    /// Writes a small shell script to ~/.local/bin/strip that forwards to the strip:// URLs.
    @discardableResult
    static func installCommandLineTool(at cliURL: URL = cliURL) throws -> URL {
        let commands = Command.all.map { "  \($0.id)\t\($0.title)" }.joined(separator: "\n")
        let layouts = LayoutPreset.allCases.map(\.rawValue).joined(separator: " ")
        let script = """
        #!/bin/sh
        # Strip command-line tool (generated by Strip).
        usage() {
          cat <<'EOF'
        Usage: strip <command>
               strip layout <\(layouts.replacingOccurrences(of: " ", with: "|"))>
               strip enable | disable | restart

        Commands:
        \(commands)
        EOF
        }
        case "$1" in
          ""|-h|--help|help) usage ;;
          list) usage | awk '/^  [a-z0-9]/{print $1}' ;;
          layout) open -g "strip://layout/$2" ;;
          enable|disable|restart) open -g "strip://$1" ;;
          *) open -g "strip://run/$1" ;;
        esac

        """
        try FileManager.default.createDirectory(at: cliURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        try script.write(to: cliURL, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: cliURL.path)
        Log.info("Installed command-line tool at \(cliURL.path)")
        return cliURL
    }

    static var isCommandLineToolOnPath: Bool {
        let path = ProcessInfo.processInfo.environment["PATH"] ?? ""
        return path.split(separator: ":").contains { $0 == cliURL.deletingLastPathComponent().path }
    }

    // MARK: Raycast

    /// One Raycast script command per Strip command. Add the folder in Raycast under
    /// Extensions → Script Commands → Add Directories.
    @discardableResult
    static func exportRaycastScripts(to raycastFolder: URL = raycastFolder) throws -> URL {
        let fm = FileManager.default
        try? fm.removeItem(at: raycastFolder)
        try fm.createDirectory(at: raycastFolder, withIntermediateDirectories: true)
        for command in Command.all {
            let script = """
            #!/bin/bash

            # Required parameters:
            # @raycast.schemaVersion 1
            # @raycast.title \(command.title)
            # @raycast.mode silent
            # @raycast.packageName Strip

            # Optional parameters:
            # @raycast.icon 🪟
            # @raycast.description Strip: \(command.id)

            open -g "strip://run/\(command.id)"

            """
            let file = raycastFolder.appendingPathComponent("strip-\(command.id).sh")
            try script.write(to: file, atomically: true, encoding: .utf8)
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: file.path)
        }
        Log.info("Exported Raycast scripts to \(raycastFolder.path)")
        return raycastFolder
    }
}
